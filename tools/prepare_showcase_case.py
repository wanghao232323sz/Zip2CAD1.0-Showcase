"""Prepare a portable inference-only library demo pack, separately from Git source."""
import argparse,json,hashlib,shutil,zipfile
from pathlib import Path

def digest(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()

def prepare(case,final,original,output):
    case,final,original,output=map(lambda p:Path(p).resolve(),(case,final,original,output))
    if output.exists():raise FileExistsError('Use a fresh bundle directory')
    rep=case/'release/reproducibility'
    inputs=[case/'joint_inputs/all.npz',case/'joint_inputs/input_contract.json',rep/'corner_inputs.npz',rep/'corner_input_contract.json',final,original]
    if not all(p.is_file() for p in inputs):raise FileNotFoundError('Case inputs, original CAD and final CAD are required')
    output.mkdir(parents=True)
    files={}
    for key,src,name in [('joint_grid',inputs[0],'joint_inputs/all.npz'),('corner_points',inputs[2],'corner_inputs.npz'),
                         ('original_cad',original,'original_library.skp'),('final_cad',final,'campus_final.skp')]:
        dest=output/name;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,dest)
        files[key]=dict(path=name,sha256=digest(dest),bytes=dest.stat().st_size)
    contract=json.loads(inputs[1].read_text(encoding='utf8'))
    contract['files']=[row for row in contract['files'] if row['file']=='all.npz']
    corner=json.loads(inputs[3].read_text(encoding='utf8'))
    for key,value,name in [('joint_contract',contract,'joint_inputs/input_contract.json'),
         ('corner_contract',dict(frame=corner['frame'],reference_roof_geometry_used=False,normalization='saved unlabelled observation frame'),'corner_contract.json')]:
        dest=output/name;dest.write_text(json.dumps(value,ensure_ascii=False,indent=2),encoding='utf8')
        files[key]=dict(path=name,sha256=digest(dest),bytes=dest.stat().st_size)
    manifest=dict(schema='zip2cad_showcase_case_v1',scene='library',files=files,
        preprocessing='Saved ZipMap observations and frozen feature grid; not recomputed during the live demo.',
        final_model_role='Precomputed full-campus showcase deliverable; not generated by the live heads.',
        training_targets_included=False,reference_cad_for_inference=False)
    (output/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf8')
    return manifest

def main():
    p=argparse.ArgumentParser(description=__doc__)
    for name in ['library-case','final-model','original-cad','output']:p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--archive',type=Path)
    a=p.parse_args();prepare(a.library_case,a.final_model,a.original_cad,a.output)
    if a.archive:
        if a.archive.exists():raise FileExistsError(a.archive)
        a.archive.parent.mkdir(parents=True,exist_ok=True)
        with zipfile.ZipFile(a.archive,'w',zipfile.ZIP_DEFLATED) as z:
            for f in sorted(a.output.rglob('*')):
                if f.is_file():z.write(f,Path('artifacts/showcase/library')/f.relative_to(a.output))
    print('Portable case prepared:',a.output)

if __name__=='__main__':main()
